interface LanguageContextType {
    language: LanguageCode;
    setLanguage: (lang: LanguageCode) => void;
    t: (key: string) => string;
    tCategory: (slug: string, fallbackName?: string) => string;
    tCategoryShort: (slug: string, fallbackName?: string) => string;
    currentLanguageOption: LanguageOption;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
    const [language, setLanguageState] = useState<LanguageCode>("en");

    useEffect(() => {
        const savedLang = localStorage.getItem("financerslot_lang") as LanguageCode;
        if (savedLang && TRANSLATIONS[savedLang]) {
            setLanguageState(savedLang);
        }
    }, []);

    const setLanguage = (lang: LanguageCode) => {
        setLanguageState(lang);
        localStorage.setItem("financerslot_lang", lang);
    };

    const t = (key: string): string => {
        return TRANSLATIONS[language]?.[key] || TRANSLATIONS.en?.[key] || key;
    };

    const tCategory = (slug: string, fallbackName?: string): string => {
        const key = `cat_${slug}`;
        return TRANSLATIONS[language]?.[key] || TRANSLATIONS.en?.[key] || fallbackName || slug;
    };

    const tCategoryShort = (slug: string, fallbackName?: string): string => {
        const key = `cat_short_${slug}`;
        return TRANSLATIONS[language]?.[key] || TRANSLATIONS.en?.[key] || tCategory(slug, fallbackName);
    };

    const currentLanguageOption = LANGUAGE_OPTIONS.find(l => l.code === language) || LANGUAGE_OPTIONS[0];

    return (
        <LanguageContext.Provider value={{ language, setLanguage, t, tCategory, tCategoryShort, currentLanguageOption }}>
            <div dir={currentLanguageOption.dir || "ltr"}>
                {children}
            </div>
        </LanguageContext.Provider>
    );
}

export function useLanguage() {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error("useLanguage must be used within a LanguageProvider");
    }
    return context;
}
